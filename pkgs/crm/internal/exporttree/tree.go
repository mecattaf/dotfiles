// Package exporttree writes the deterministic Markdown projection produced by
// crm export tree. The database remains authoritative; every successful run
// replaces one ownership-marked generated tree wholesale.
package exporttree

import (
	"errors"
	"fmt"
	"net/url"
	"os"
	"path/filepath"
	"strconv"
	"strings"
	"unicode"

	"github.com/mecattaf/crm/internal/model"
)

const generatedMarker = "<!-- generated by crm export tree; do not edit -->"

const readme = generatedMarker + `
# CRM Markdown tree

This directory is a generated, git-diffable view of the live records in
crm.db. The database is authoritative: edit records with the crm CLI, then
regenerate this tree. Manual changes here are discarded on the next export.

## Layout

- index.md links every exported record.
- orgs/ contains one Markdown file per live organization.
- contacts/ contains one Markdown file per live contact and its timeline.
- deals/ contains one Markdown file per live deal and its stage history.
- interactions/ contains one Markdown file per live interaction.

Transcript links point back to the evidence files stored under the directory
containing crm.db. Archived records are omitted from this live projection;
flat JSON and CSV exports retain them for backup and inspection.
`

// ContactDocument carries the contact, its optional organization, and its
// assembled live timeline into the filesystem-only renderer.
type ContactDocument struct {
	Contact  model.Contact
	Org      *model.Org
	Timeline []model.Interaction
}

// OrgDocument carries an organization and its assembled live timeline.
type OrgDocument struct {
	Org      model.Org
	Timeline []model.Interaction
}

// DealDocument carries a deal plus its real-columned history and merged
// timeline.
type DealDocument struct {
	Detail model.DealDetail
}

// Snapshot is the complete live projection. Collection order is retained in
// the generated index and should therefore already be deterministic.
type Snapshot struct {
	Orgs         []OrgDocument
	Contacts     []ContactDocument
	Deals        []DealDocument
	Interactions []model.Interaction
}

type treePaths struct {
	orgs         map[int64]string
	contacts     map[int64]string
	deals        map[int64]string
	interactions map[int64]string
}

type pathCandidate struct {
	id   int64
	ref  string
	name string
}

// Write resolves destination, renders a complete staging tree, and swaps it
// into place. A nonempty pre-existing directory must carry our generated
// marker, preventing a typo from replacing an unrelated directory.
func Write(destination, transcriptBase string, snapshot Snapshot) (string, error) {
	absoluteDestination, err := filepath.Abs(destination)
	if err != nil {
		return "", fmt.Errorf("resolve export tree destination %s: %w", destination, err)
	}
	absoluteDestination = filepath.Clean(absoluteDestination)
	if err := validateDestination(absoluteDestination); err != nil {
		return "", err
	}

	absoluteBase, err := filepath.Abs(transcriptBase)
	if err != nil {
		return "", fmt.Errorf("resolve transcript base %s: %w", transcriptBase, err)
	}
	absoluteBase = filepath.Clean(absoluteBase)

	parent := filepath.Dir(absoluteDestination)
	if err := os.MkdirAll(parent, 0o700); err != nil {
		return "", fmt.Errorf("create export tree parent %s: %w", parent, err)
	}
	staging, err := os.MkdirTemp(parent, "."+filepath.Base(absoluteDestination)+".tmp-")
	if err != nil {
		return "", fmt.Errorf("create export tree staging directory: %w", err)
	}
	defer func() {
		_ = os.RemoveAll(staging)
	}()

	paths := assignTreePaths(snapshot)
	if err := writeSnapshot(staging, absoluteDestination, absoluteBase, snapshot, paths); err != nil {
		return "", err
	}
	if err := replaceDestination(staging, absoluteDestination); err != nil {
		return "", err
	}

	return absoluteDestination, nil
}

func validateDestination(destination string) error {
	info, err := os.Lstat(destination)
	if errors.Is(err, os.ErrNotExist) {
		return nil
	}
	if err != nil {
		return fmt.Errorf("inspect export tree destination %s: %w", destination, err)
	}
	if info.Mode()&os.ModeSymlink != 0 {
		return model.NewExitError(
			model.ErrValidation,
			"export tree destination %q is a symlink — choose a real directory",
			destination,
		)
	}
	if !info.IsDir() {
		return model.NewExitError(
			model.ErrValidation,
			"export tree destination %q is not a directory",
			destination,
		)
	}

	entries, err := os.ReadDir(destination)
	if err != nil {
		return fmt.Errorf("read export tree destination %s: %w", destination, err)
	}
	if len(entries) == 0 {
		return nil
	}
	readmeBytes, err := os.ReadFile(filepath.Join(destination, "README.md"))
	if err == nil && strings.Contains(string(readmeBytes), generatedMarker) {
		return nil
	}
	if err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("read export tree marker in %s: %w", destination, err)
	}

	return model.NewExitError(
		model.ErrValidation,
		"export tree destination %q is not empty and is not a generated CRM tree",
		destination,
	)
}

func writeSnapshot(
	staging string,
	destination string,
	transcriptBase string,
	snapshot Snapshot,
	paths treePaths,
) error {
	for _, directory := range []string{"orgs", "contacts", "deals", "interactions"} {
		if err := os.MkdirAll(filepath.Join(staging, directory), 0o700); err != nil {
			return fmt.Errorf("create export tree %s directory: %w", directory, err)
		}
	}
	if err := writeGeneratedFile(filepath.Join(staging, "README.md"), readme); err != nil {
		return err
	}
	index, err := renderIndex(snapshot, paths)
	if err != nil {
		return err
	}
	if err := writeGeneratedFile(filepath.Join(staging, "index.md"), index); err != nil {
		return err
	}

	for _, document := range snapshot.Orgs {
		relativePath := paths.orgs[document.Org.ID]
		content, renderErr := renderOrg(
			document,
			relativePath,
			destination,
			transcriptBase,
			paths,
			snapshot.Contacts,
		)
		if renderErr != nil {
			return renderErr
		}
		if err := writeGeneratedFile(filepath.Join(staging, relativePath), content); err != nil {
			return err
		}
	}
	for _, document := range snapshot.Contacts {
		relativePath := paths.contacts[document.Contact.ID]
		content, renderErr := renderContact(
			document,
			relativePath,
			destination,
			transcriptBase,
			paths,
		)
		if renderErr != nil {
			return renderErr
		}
		if err := writeGeneratedFile(filepath.Join(staging, relativePath), content); err != nil {
			return err
		}
	}
	for _, document := range snapshot.Deals {
		relativePath := paths.deals[document.Detail.ID]
		content, renderErr := renderDeal(
			document,
			relativePath,
			destination,
			transcriptBase,
			paths,
		)
		if renderErr != nil {
			return renderErr
		}
		if err := writeGeneratedFile(filepath.Join(staging, relativePath), content); err != nil {
			return err
		}
	}
	for _, interaction := range snapshot.Interactions {
		relativePath := paths.interactions[interaction.ID]
		content, renderErr := renderInteraction(
			interaction,
			relativePath,
			destination,
			transcriptBase,
			paths,
		)
		if renderErr != nil {
			return renderErr
		}
		if err := writeGeneratedFile(filepath.Join(staging, relativePath), content); err != nil {
			return err
		}
	}

	return nil
}

func writeGeneratedFile(path, content string) error {
	if err := os.WriteFile(path, []byte(content), 0o600); err != nil {
		return fmt.Errorf("write generated export file %s: %w", path, err)
	}

	return nil
}

func replaceDestination(staging, destination string) error {
	_, err := os.Lstat(destination)
	if errors.Is(err, os.ErrNotExist) {
		if err := os.Rename(staging, destination); err != nil {
			return fmt.Errorf("install generated export tree at %s: %w", destination, err)
		}

		return nil
	}
	if err != nil {
		return fmt.Errorf("inspect export tree destination before replacement: %w", err)
	}

	parent := filepath.Dir(destination)
	backup, err := os.MkdirTemp(parent, "."+filepath.Base(destination)+".old-")
	if err != nil {
		return fmt.Errorf("reserve export tree backup path: %w", err)
	}
	if err := os.Remove(backup); err != nil {
		return fmt.Errorf("prepare export tree backup path: %w", err)
	}
	if err := os.Rename(destination, backup); err != nil {
		return fmt.Errorf("move previous export tree aside: %w", err)
	}
	if err := os.Rename(staging, destination); err != nil {
		restoreErr := os.Rename(backup, destination)
		if restoreErr != nil {
			return errors.Join(
				fmt.Errorf("install generated export tree: %w", err),
				fmt.Errorf("restore previous export tree: %w", restoreErr),
			)
		}

		return fmt.Errorf("install generated export tree: %w", err)
	}
	if err := os.RemoveAll(backup); err != nil {
		return fmt.Errorf("remove replaced export tree %s: %w", backup, err)
	}

	return nil
}

func assignTreePaths(snapshot Snapshot) treePaths {
	orgCandidates := make([]pathCandidate, 0, len(snapshot.Orgs))
	for _, document := range snapshot.Orgs {
		orgCandidates = append(orgCandidates, pathCandidate{
			id: document.Org.ID, ref: document.Org.Reference(), name: document.Org.Name,
		})
	}
	contactCandidates := make([]pathCandidate, 0, len(snapshot.Contacts))
	for _, document := range snapshot.Contacts {
		contactCandidates = append(contactCandidates, pathCandidate{
			id:   document.Contact.ID,
			ref:  document.Contact.Reference(),
			name: document.Contact.Name,
		})
	}
	dealCandidates := make([]pathCandidate, 0, len(snapshot.Deals))
	for _, document := range snapshot.Deals {
		dealCandidates = append(dealCandidates, pathCandidate{
			id:   document.Detail.ID,
			ref:  document.Detail.Reference(),
			name: document.Detail.Title,
		})
	}
	interactionCandidates := make([]pathCandidate, 0, len(snapshot.Interactions))
	for _, interaction := range snapshot.Interactions {
		interactionCandidates = append(interactionCandidates, pathCandidate{
			id:   interaction.ID,
			ref:  interaction.Reference(),
			name: interaction.OccurredOn + " " + interaction.Kind + " " + interaction.Reference(),
		})
	}

	return treePaths{
		orgs:         assignEntityPaths("orgs", orgCandidates),
		contacts:     assignEntityPaths("contacts", contactCandidates),
		deals:        assignEntityPaths("deals", dealCandidates),
		interactions: assignEntityPaths("interactions", interactionCandidates),
	}
}

func assignEntityPaths(directory string, candidates []pathCandidate) map[int64]string {
	baseByID := make(map[int64]string, len(candidates))
	counts := make(map[string]int, len(candidates))
	for _, candidate := range candidates {
		base := slugify(candidate.name)
		if base == "" {
			base = candidate.ref
		}
		baseByID[candidate.id] = base
		counts[base]++
	}

	paths := make(map[int64]string, len(candidates))
	for _, candidate := range candidates {
		base := baseByID[candidate.id]
		if counts[base] > 1 {
			base += "-" + candidate.ref
		}
		paths[candidate.id] = filepath.Join(directory, base+".md")
	}

	return paths
}

func slugify(value string) string {
	normalized, _ := model.TryNormalizeName(value)
	var slug strings.Builder
	lastDash := false
	runes := 0
	for _, current := range normalized {
		if unicode.IsLetter(current) || unicode.IsDigit(current) {
			if runes >= 60 {
				break
			}
			slug.WriteRune(current)
			lastDash = false
			runes++
			continue
		}
		if slug.Len() > 0 && !lastDash {
			slug.WriteByte('-')
			lastDash = true
		}
	}

	return strings.Trim(slug.String(), "-")
}

func renderIndex(snapshot Snapshot, paths treePaths) (string, error) {
	var document strings.Builder
	document.WriteString("# CRM index\n\n")
	document.WriteString("This index and every linked file are generated from crm.db.\n")
	if err := writeIndexSection(&document, "Organizations", orgIndexEntries(snapshot.Orgs), paths.orgs); err != nil {
		return "", err
	}
	if err := writeIndexSection(&document, "Contacts", contactIndexEntries(snapshot.Contacts), paths.contacts); err != nil {
		return "", err
	}
	if err := writeIndexSection(&document, "Deals", dealIndexEntries(snapshot.Deals), paths.deals); err != nil {
		return "", err
	}
	if err := writeIndexSection(
		&document,
		"Interactions",
		interactionIndexEntries(snapshot.Interactions),
		paths.interactions,
	); err != nil {
		return "", err
	}

	return document.String(), nil
}

type indexEntry struct {
	id    int64
	label string
	ref   string
}

func orgIndexEntries(documents []OrgDocument) []indexEntry {
	entries := make([]indexEntry, 0, len(documents))
	for _, document := range documents {
		entries = append(entries, indexEntry{
			id: document.Org.ID, label: document.Org.Name, ref: document.Org.Reference(),
		})
	}

	return entries
}

func contactIndexEntries(documents []ContactDocument) []indexEntry {
	entries := make([]indexEntry, 0, len(documents))
	for _, document := range documents {
		entries = append(entries, indexEntry{
			id:    document.Contact.ID,
			label: document.Contact.Name,
			ref:   document.Contact.Reference(),
		})
	}

	return entries
}

func dealIndexEntries(documents []DealDocument) []indexEntry {
	entries := make([]indexEntry, 0, len(documents))
	for _, document := range documents {
		entries = append(entries, indexEntry{
			id:    document.Detail.ID,
			label: document.Detail.Title,
			ref:   document.Detail.Reference(),
		})
	}

	return entries
}

func interactionIndexEntries(interactions []model.Interaction) []indexEntry {
	entries := make([]indexEntry, 0, len(interactions))
	for _, interaction := range interactions {
		entries = append(entries, indexEntry{
			id:    interaction.ID,
			label: interaction.OccurredOn + " — " + interaction.Kind + " — " + interaction.Summary,
			ref:   interaction.Reference(),
		})
	}

	return entries
}

func writeIndexSection(
	document *strings.Builder,
	title string,
	entries []indexEntry,
	paths map[int64]string,
) error {
	_, _ = fmt.Fprintf(document, "\n## %s (%d)\n\n", title, len(entries))
	if len(entries) == 0 {
		document.WriteString("None.\n")

		return nil
	}
	for _, entry := range entries {
		target, found := paths[entry.id]
		if !found {
			return fmt.Errorf("render index: missing path for %s", entry.ref)
		}
		_, _ = fmt.Fprintf(
			document,
			"- [%s (%s)](%s)\n",
			markdownInline(entry.label),
			entry.ref,
			markdownPath(target),
		)
	}

	return nil
}

func renderContact(
	document ContactDocument,
	currentPath string,
	destination string,
	transcriptBase string,
	paths treePaths,
) (string, error) {
	contact := document.Contact
	var output strings.Builder
	output.WriteString("---\n")
	_, _ = fmt.Fprintf(&output, "id: %s\n", contact.Reference())
	_, _ = fmt.Fprintf(&output, "org: %s\n", yamlOptionalRef("o", contact.OrgID))
	_, _ = fmt.Fprintf(&output, "email: %s\n", yamlOptionalString(contact.Email))
	writeProvenance(&output, contact.ProvenanceSources, contact.ProvenanceDetails)
	output.WriteString("---\n\n")
	_, _ = fmt.Fprintf(&output, "# %s (%s)\n", markdownInline(contact.Name), contact.Reference())
	writeOptionalMarkdownLine(&output, "Title", contact.JobTitle)
	writeOptionalMarkdownLine(&output, "Phone", contact.Phone)
	writeOptionalMarkdownLine(&output, "Location", contact.Location)
	writeOptionalMarkdownLine(&output, "Relationship", contact.RelationshipHint)
	if contact.LinkedIn != nil {
		_, _ = fmt.Fprintf(
			&output,
			"- LinkedIn: https://www.linkedin.com/in/%s\n",
			markdownInline(*contact.LinkedIn),
		)
	}
	if document.Org != nil {
		organization := document.Org
		if target, found := paths.orgs[organization.ID]; found {
			link, err := relativeTreeLink(currentPath, target)
			if err != nil {
				return "", err
			}
			_, _ = fmt.Fprintf(
				&output,
				"- Organization: [%s (%s)](%s)\n",
				markdownInline(organization.Name),
				organization.Reference(),
				link,
			)
		} else {
			_, _ = fmt.Fprintf(
				&output,
				"- Organization: %s (%s)\n",
				markdownInline(organization.Name),
				organization.Reference(),
			)
		}
	}
	writeMarkdownSection(&output, "Dossier", contact.Context)
	if len(contact.Links) > 0 {
		output.WriteString("\n## Relationships\n\n")
		for _, link := range contact.Links {
			label := markdownInline(link.Contact.Name) + " (" + link.Contact.Reference() + ")"
			if target, found := paths.contacts[link.Contact.ID]; found {
				relative, err := relativeTreeLink(currentPath, target)
				if err != nil {
					return "", err
				}
				label = "[" + label + "](" + relative + ")"
			}
			_, _ = fmt.Fprintf(
				&output,
				"- %s %s %s",
				label,
				markdownInline(link.Direction),
				markdownInline(link.Type),
			)
			if link.Note != nil {
				_, _ = fmt.Fprintf(&output, " — %s", markdownInline(*link.Note))
			}
			output.WriteByte('\n')
		}
	}
	if err := writeInteractionTimeline(
		&output,
		document.Timeline,
		currentPath,
		destination,
		transcriptBase,
		paths.interactions,
	); err != nil {
		return "", err
	}

	return output.String(), nil
}

func renderOrg(
	document OrgDocument,
	currentPath string,
	destination string,
	transcriptBase string,
	paths treePaths,
	contacts []ContactDocument,
) (string, error) {
	organization := document.Org
	var output strings.Builder
	output.WriteString("---\n")
	_, _ = fmt.Fprintf(&output, "id: %s\n", organization.Reference())
	_, _ = fmt.Fprintf(&output, "website: %s\n", yamlOptionalString(organization.Website))
	writeProvenance(&output, organization.ProvenanceSources, organization.ProvenanceDetails)
	output.WriteString("---\n\n")
	_, _ = fmt.Fprintf(
		&output,
		"# %s (%s)\n",
		markdownInline(organization.Name),
		organization.Reference(),
	)
	writeOptionalMarkdownLine(&output, "Category", organization.Category)
	writeOptionalMarkdownLine(&output, "Location", organization.Location)
	writeOptionalMarkdownLine(&output, "Focus", organization.Focus)
	writeOptionalMarkdownLine(&output, "Relationship", organization.RelationshipHint)
	if organization.LinkedIn != nil {
		_, _ = fmt.Fprintf(
			&output,
			"- LinkedIn: https://www.linkedin.com/company/%s\n",
			markdownInline(*organization.LinkedIn),
		)
	}
	writeMarkdownSection(&output, "Dossier", organization.Context)

	linkedContacts := make([]ContactDocument, 0)
	for _, contact := range contacts {
		if contact.Contact.OrgID != nil && *contact.Contact.OrgID == organization.ID {
			linkedContacts = append(linkedContacts, contact)
		}
	}
	if len(linkedContacts) > 0 {
		output.WriteString("\n## Contacts\n\n")
		for _, contact := range linkedContacts {
			target := paths.contacts[contact.Contact.ID]
			relative, err := relativeTreeLink(currentPath, target)
			if err != nil {
				return "", err
			}
			_, _ = fmt.Fprintf(
				&output,
				"- [%s (%s)](%s)\n",
				markdownInline(contact.Contact.Name),
				contact.Contact.Reference(),
				relative,
			)
		}
	}
	if err := writeInteractionTimeline(
		&output,
		document.Timeline,
		currentPath,
		destination,
		transcriptBase,
		paths.interactions,
	); err != nil {
		return "", err
	}

	return output.String(), nil
}

func renderDeal(
	document DealDocument,
	currentPath string,
	destination string,
	transcriptBase string,
	paths treePaths,
) (string, error) {
	detail := document.Detail
	deal := detail.Deal
	var output strings.Builder
	output.WriteString("---\n")
	_, _ = fmt.Fprintf(&output, "id: %s\n", deal.Reference())
	_, _ = fmt.Fprintf(&output, "org: %s\n", yamlOptionalRef("o", deal.OrgID))
	_, _ = fmt.Fprintf(&output, "contact: %s\n", yamlOptionalRef("c", deal.ContactID))
	_, _ = fmt.Fprintf(&output, "pipeline: p%d\n", deal.PipelineID)
	_, _ = fmt.Fprintf(&output, "stage: s%d\n", deal.StageID)
	_, _ = fmt.Fprintf(&output, "status: %s\n", deal.Status)
	output.WriteString("---\n\n")
	_, _ = fmt.Fprintf(&output, "# %s (%s)\n", markdownInline(deal.Title), deal.Reference())
	_, _ = fmt.Fprintf(&output, "- Pipeline: %s (p%d)\n", markdownInline(deal.Pipeline), deal.PipelineID)
	_, _ = fmt.Fprintf(&output, "- Stage: %s (s%d)\n", markdownInline(deal.Stage), deal.StageID)
	_, _ = fmt.Fprintf(&output, "- Status: %s\n", deal.Status)
	writeOptionalMarkdownLine(&output, "Outcome", deal.OutcomeReason)

	output.WriteString("\n## Stage history\n\n")
	if len(detail.StageMoves) == 0 {
		output.WriteString("No stage moves.\n")
	} else {
		for _, move := range detail.StageMoves {
			from := "created"
			if move.FromStageName != nil {
				from = *move.FromStageName
			}
			_, _ = fmt.Fprintf(
				&output,
				"- %s — %s → %s",
				move.MovedAt,
				markdownInline(from),
				markdownInline(move.ToStageName),
			)
			if move.Note != nil {
				_, _ = fmt.Fprintf(&output, " — %s", markdownInline(*move.Note))
			}
			output.WriteByte('\n')
		}
	}

	output.WriteString("\n## Timeline\n\n")
	if len(detail.Timeline) == 0 {
		output.WriteString("No recorded events.\n")

		return output.String(), nil
	}
	for _, entry := range detail.Timeline {
		if entry.StageMove != nil {
			move := entry.StageMove
			from := "created"
			if move.FromStageName != nil {
				from = *move.FromStageName
			}
			_, _ = fmt.Fprintf(
				&output,
				"- %s — stage — %s → %s",
				move.MovedAt,
				markdownInline(from),
				markdownInline(move.ToStageName),
			)
			if move.Note != nil {
				_, _ = fmt.Fprintf(&output, " — %s", markdownInline(*move.Note))
			}
			output.WriteByte('\n')
			continue
		}
		if entry.Interaction != nil {
			if err := writeInteractionTimelineEntry(
				&output,
				*entry.Interaction,
				currentPath,
				destination,
				transcriptBase,
				paths.interactions,
			); err != nil {
				return "", err
			}
		}
	}

	return output.String(), nil
}

func renderInteraction(
	interaction model.Interaction,
	currentPath string,
	destination string,
	transcriptBase string,
	paths treePaths,
) (string, error) {
	var output strings.Builder
	output.WriteString("---\n")
	_, _ = fmt.Fprintf(&output, "id: %s\n", interaction.Reference())
	_, _ = fmt.Fprintf(&output, "kind: %s\n", interaction.Kind)
	_, _ = fmt.Fprintf(&output, "date: %s\n", interaction.OccurredOn)
	_, _ = fmt.Fprintf(&output, "org: %s\n", yamlOptionalRef("o", interaction.OrgID))
	_, _ = fmt.Fprintf(&output, "deal: %s\n", yamlOptionalRef("d", interaction.DealID))
	_, _ = fmt.Fprintf(&output, "contacts: %s\n", yamlContactRefs(interaction.ContactIDs))
	_, _ = fmt.Fprintf(&output, "transcript: %s\n", yamlOptionalString(interaction.TranscriptPath))
	output.WriteString("---\n\n")
	_, _ = fmt.Fprintf(
		&output,
		"# %s — %s (%s)\n\n",
		interaction.OccurredOn,
		interaction.Kind,
		interaction.Reference(),
	)
	output.WriteString(interaction.Summary)
	output.WriteByte('\n')
	writeMarkdownSection(&output, "Body", interaction.Body)
	if interaction.TranscriptPath != nil {
		link, err := relativeTranscriptLink(
			destination,
			currentPath,
			transcriptBase,
			*interaction.TranscriptPath,
		)
		if err != nil {
			return "", err
		}
		_, _ = fmt.Fprintf(&output, "\n[Open transcript](%s)\n", link)
	}
	if interaction.DealID != nil {
		if target, found := paths.deals[*interaction.DealID]; found {
			link, err := relativeTreeLink(currentPath, target)
			if err != nil {
				return "", err
			}
			_, _ = fmt.Fprintf(&output, "\nDeal: [%s](%s)\n", prefixedRef("d", *interaction.DealID), link)
		}
	}

	return output.String(), nil
}

func writeInteractionTimeline(
	output *strings.Builder,
	timeline []model.Interaction,
	currentPath string,
	destination string,
	transcriptBase string,
	interactionPaths map[int64]string,
) error {
	output.WriteString("\n## Timeline\n\n")
	if len(timeline) == 0 {
		output.WriteString("No recorded interactions.\n")

		return nil
	}
	for _, interaction := range timeline {
		if err := writeInteractionTimelineEntry(
			output,
			interaction,
			currentPath,
			destination,
			transcriptBase,
			interactionPaths,
		); err != nil {
			return err
		}
	}

	return nil
}

func writeInteractionTimelineEntry(
	output *strings.Builder,
	interaction model.Interaction,
	currentPath string,
	destination string,
	transcriptBase string,
	interactionPaths map[int64]string,
) error {
	ref := interaction.Reference()
	refLabel := ref
	if target, found := interactionPaths[interaction.ID]; found {
		link, err := relativeTreeLink(currentPath, target)
		if err != nil {
			return err
		}
		refLabel = "[" + ref + "](" + link + ")"
	}
	_, _ = fmt.Fprintf(
		output,
		"- %s — %s — %s — %s",
		interaction.OccurredOn,
		interaction.Kind,
		refLabel,
		markdownInline(interaction.Summary),
	)
	if interaction.TranscriptPath != nil {
		link, err := relativeTranscriptLink(
			destination,
			currentPath,
			transcriptBase,
			*interaction.TranscriptPath,
		)
		if err != nil {
			return err
		}
		_, _ = fmt.Fprintf(output, " ([transcript](%s))", link)
	}
	output.WriteByte('\n')

	return nil
}

func writeProvenance(output *strings.Builder, sources, details *string) {
	output.WriteString("provenance:\n")
	_, _ = fmt.Fprintf(output, "  sources: %s\n", yamlOptionalString(sources))
	_, _ = fmt.Fprintf(output, "  details: %s\n", yamlOptionalString(details))
}

func writeOptionalMarkdownLine(output *strings.Builder, label string, value *string) {
	if value == nil {
		return
	}
	_, _ = fmt.Fprintf(output, "- %s: %s\n", label, markdownInline(*value))
}

func writeMarkdownSection(output *strings.Builder, heading string, value *string) {
	if value == nil {
		return
	}
	_, _ = fmt.Fprintf(output, "\n## %s\n\n", heading)
	output.WriteString(*value)
	if !strings.HasSuffix(*value, "\n") {
		output.WriteByte('\n')
	}
}

func yamlOptionalRef(prefix string, id *int64) string {
	if id == nil {
		return "null"
	}

	return prefixedRef(prefix, *id)
}

func yamlOptionalString(value *string) string {
	if value == nil {
		return "null"
	}

	return strconv.Quote(*value)
}

func yamlContactRefs(ids []int64) string {
	if len(ids) == 0 {
		return "[]"
	}
	refs := make([]string, len(ids))
	for index, id := range ids {
		refs[index] = prefixedRef("c", id)
	}

	return "[" + strings.Join(refs, ", ") + "]"
}

func prefixedRef(prefix string, id int64) string {
	return prefix + strconv.FormatInt(id, 10)
}

func markdownInline(value string) string {
	value = strings.Join(strings.Fields(value), " ")
	replacer := strings.NewReplacer(
		"\\", "\\\\",
		"[", "\\[",
		"]", "\\]",
	)

	return replacer.Replace(value)
}

func relativeTreeLink(from, to string) (string, error) {
	relative, err := filepath.Rel(filepath.Dir(from), to)
	if err != nil {
		return "", fmt.Errorf("render relative tree link from %s to %s: %w", from, to, err)
	}

	return markdownPath(relative), nil
}

func relativeTranscriptLink(
	destination string,
	currentPath string,
	transcriptBase string,
	storedPath string,
) (string, error) {
	target := filepath.Join(transcriptBase, filepath.FromSlash(storedPath))
	relativeToBase, err := filepath.Rel(transcriptBase, target)
	if err != nil {
		return "", fmt.Errorf("resolve transcript link %s: %w", storedPath, err)
	}
	if relativeToBase == ".." || strings.HasPrefix(relativeToBase, ".."+string(filepath.Separator)) {
		return "", model.NewExitError(
			model.ErrValidation,
			"stored transcript path %q is outside transcript base %q",
			storedPath,
			transcriptBase,
		)
	}
	fromDirectory := filepath.Dir(filepath.Join(destination, currentPath))
	relative, err := filepath.Rel(fromDirectory, target)
	if err != nil {
		return "", fmt.Errorf("render transcript link for %s: %w", storedPath, err)
	}

	return markdownPath(relative), nil
}

func markdownPath(path string) string {
	parts := strings.Split(filepath.ToSlash(path), "/")
	for index, part := range parts {
		if part == "." || part == ".." || part == "" {
			continue
		}
		parts[index] = url.PathEscape(part)
	}

	return strings.Join(parts, "/")
}
