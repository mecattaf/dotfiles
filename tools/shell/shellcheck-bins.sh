#!/usr/bin/env bash
# tools/shell/shellcheck-bins.sh: runs shellcheck over every shell script in
# home/dot_local/bin and write one Markdown report with a per file table of
# warning counts and the SC codes seen.
#
# What it is: a read only lint pass, written 2026-10-22 for the shell
# consolidation dry run (docs/shell/PROJECTOR.md links its output). It never
# executes a script under home/dot_local/bin; shellcheck only parses them.
# What it replaced: nothing; before this there was no repo wide shellcheck of
# the user bins.
# Deliberately absent: no auto fix, no exit status gate (the report is
# evidence, not a CI check yet), no network (nix runs with --offline).
#
# Usage: tools/shell/shellcheck-bins.sh [OUTPUT.md]
#   OUTPUT.md defaults to standard output.
# Shellcheck resolution, in order: shellcheck on PATH; then
#   nix run --offline --inputs-from <repo> nixpkgs#shellcheck
#   (the flake's own pinned nixpkgs, from the local store only); else the
#   report states that shellcheck was unavailable.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
bindir="$repo/home/dot_local/bin"
out="${1:-/dev/stdout}"

sc=()
sc_source=""
if command -v shellcheck >/dev/null 2>&1; then
  sc=(shellcheck)
  sc_source="shellcheck on PATH ($(command -v shellcheck))"
elif command -v nix >/dev/null 2>&1 &&
  nix run --offline --inputs-from "$repo" nixpkgs#shellcheck -- --version >/dev/null 2>&1; then
  # Resolve the store path once so nix's own warnings stay out of the report.
  sc_bin="$(nix shell --offline --inputs-from "$repo" nixpkgs#shellcheck -c sh -c 'command -v shellcheck' 2>/dev/null)"
  sc=("$sc_bin")
  sc_source="nix --offline --inputs-from $repo nixpkgs#shellcheck ($sc_bin)"
fi

# Shell scripts by shebang only; Python, ELF and directories are skipped.
files=()
for f in "$bindir"/*; do
  [ -f "$f" ] || continue
  first="$(head -n1 "$f" 2>/dev/null | tr -d '\0' || true)"
  case "$first" in
    '#!'*bash* | '#!'*/sh | '#!'*'env sh'*) files+=("$f") ;;
  esac
done

{
  echo "# shellcheck over home/dot_local/bin"
  echo
  echo "Generated by \`tools/shell/shellcheck-bins.sh\` on $(date -u +%Y-%m-%dT%H:%MZ)."
  echo "Repo: \`$repo\` at \`$(git -C "$repo" rev-parse --short HEAD 2>/dev/null || echo unknown)\`."
  echo
  if [ "${#sc[@]}" -eq 0 ]; then
    echo "shellcheck was unavailable: not on PATH and not reachable with"
    echo "\`nix run --offline --inputs-from $repo nixpkgs#shellcheck\`. No file was checked."
    echo
    echo "## Not verified"
    echo
    echo "Every script in home/dot_local/bin: shellcheck was absent."
    exit 0
  fi
  version="$("${sc[@]}" --version 2>/dev/null | awk '/^version:/ {print $2}')"
  echo "Shellcheck: $sc_source, version $version. Default severity (style and up), shell taken from each shebang."
  echo
  echo "| file | shebang | errors | warnings | info or style | total | codes |"
  echo "| --- | --- | ---: | ---: | ---: | ---: | --- |"
  t_err=0 t_warn=0 t_info=0 clean=0
  for f in "${files[@]}"; do
    name="${f##*/}"
    shebang="$(head -n1 "$f" | sed 's/^#!//; s/|/\\|/g')"
    # gcc format: file:line:col: severity: message [SCxxxx]
    report="$("${sc[@]}" -f gcc -x "$f" 2>&1 || true)"
    e=$(grep -c ': error: ' <<<"$report" || true)
    w=$(grep -c ': warning: ' <<<"$report" || true)
    i=$(grep -c ': note: ' <<<"$report" || true)
    codes="$(grep -o '\[SC[0-9]*\]' <<<"$report" | tr -d '[]' | sort | uniq -c | awk '{printf "%s%s x%s", (NR>1?", ":""), $2, $1}' || true)"
    total=$((e + w + i))
    if [ "$total" -eq 0 ]; then clean=$((clean + 1)); fi
    t_err=$((t_err + e)) t_warn=$((t_warn + w)) t_info=$((t_info + i))
    echo "| $name | \`$shebang\` | $e | $w | $i | $total | ${codes:-none} |"
  done
  echo
  echo "Totals: ${#files[@]} shell files, $clean clean, $t_err errors, $t_warn warnings, $t_info info or style notes."
  echo
  echo "Note: shellcheck's gcc output prints both info and style findings as \`note\`,"
  echo "so they share one column."
  echo
  echo "## Findings, verbatim (gcc format)"
  echo
  echo '```'
  for f in "${files[@]}"; do
    "${sc[@]}" -f gcc -x "$f" 2>&1 | sed "s|^$repo/||" || true
  done
  echo '```'
} >"$out"
